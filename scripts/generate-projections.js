#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const root = path.resolve(__dirname, "..");
function value(flag, fallback) { const i = process.argv.indexOf(flag); return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback; }
const output = path.resolve(value("--output", path.join(root, ".ai-workflow", "generated")));
const profile = value("--profile", "pilot-read-only");
const config = JSON.parse(fs.readFileSync(path.join(root, ".ai-workflow/config.json"), "utf8"));
const registry = JSON.parse(fs.readFileSync(path.join(root, ".ai-workflow/adapter-registry.json"), "utf8"));
const policy = JSON.parse(fs.readFileSync(path.join(root, "mcp-permission-policy.json"), "utf8"));
const selectedProfile = policy.profiles?.[profile];
if (!selectedProfile) { console.error(`PROJECTION_PROFILE_UNKNOWN: ${profile}`); process.exit(1); }
const skillDir = path.join(root, ".opencode/skills");
const skills = fs.existsSync(skillDir) ? fs.readdirSync(skillDir).filter((name) => fs.existsSync(path.join(skillDir, name, "SKILL.md"))).sort() : [];
const header = "<!-- Generated by AI Workflow. Edit canonical sources, not this projection. -->\n";
const body = [
  "# AI Workflow Runtime Projection",
  "",
  `Canonical configuration: ${config.canonical_root}`,
  `MCP profile: ${profile}`,
  `Allowed MCP servers: ${(selectedProfile.enabled_servers || []).join(", ")}`,
  `Disabled MCP servers: ${(selectedProfile.disabled_servers || []).join(", ")}`,
  "",
  "## Safety contract",
  "",
  "Use the canonical AI Workflow adapter boundary. Do not perform writes, deployments, messaging, browser actions, payments, or account changes without an explicit approval request and the central idempotency/budget guards.",
  "",
  `Canonical skill count: ${skills.length}`,
  "",
  "## Canonical skills",
  "",
  ...skills.map((skill) => `- ${skill}`),
  "",
].join("\n");
const files = {
  "AGENTS.md": `${header}${body}`,
  "CLAUDE.md": `${header}${body}`,
  "GEMINI.md": `${header}${body}`,
  "cursor/rules/AI-Workflow.md": `${header}${body}`,
  "github-copilot/AI-Workflow.md": `${header}${body}`,
  "cline-roo/AI-Workflow.md": `${header}${body}`,
  "windsurf/AI-Workflow.md": `${header}${body}`,
  "mcp-policy.json": JSON.stringify({ policy_version: policy.policy_version, profile, enabled_servers: selectedProfile.enabled_servers, disabled_servers: selectedProfile.disabled_servers, allowed_capabilities: selectedProfile.allowed_capabilities, allowed_external_writes: selectedProfile.allowed_external_writes }, null, 2) + "\n",
  "adapter-registry.json": JSON.stringify({ registry_version: registry.registry_version, default_adapter: registry.default_adapter, adapters: registry.adapters }, null, 2) + "\n",
};
const manifest = { projection_version: "1.0.0", generated_at: "deterministic", profile, source_config: ".ai-workflow/config.json", files: {} };
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true, mode: 0o700 });
for (const [relative, content] of Object.entries(files)) {
  const target = path.join(output, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  fs.writeFileSync(target, content, { encoding: "utf8", mode: 0o600 });
  manifest.files[relative] = { bytes: Buffer.byteLength(content), sha256: crypto.createHash("sha256").update(content).digest("hex") };
}
fs.writeFileSync(path.join(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, { encoding: "utf8", mode: 0o600 });
console.log(`Generated ${Object.keys(files).length} deterministic runtime projections at ${path.relative(root, output)}`);
console.log(JSON.stringify({ output: path.relative(root, output), profile, files: Object.keys(files).length, canonical_skills: skills.length }, null, 2));
